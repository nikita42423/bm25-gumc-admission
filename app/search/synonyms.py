def expand(terms: list[str]) -> list[str]:
    """Термы вопроса + их синонимы (значения тоже лемматизируем, как документы)."""
    from .preprocess import lemma

    out = list(terms)
    for t in terms:
        out += [lemma(v) for v in SYNONYMS.get(t, [])]
    return out
